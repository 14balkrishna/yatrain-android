// ── Combined search list (deduped by code) ─────────────────────────────────────

val allStationsForSearch: List<StationInfo> by lazy {
    val seen = mutableSetOf<String>()
    searchStations.filter { seen.add(it.code.uppercase()) }
}

/** Returns the nearest station from the curated list using Euclidean distance on lat/lng. */
fun nearestStation(lat: Double, lng: Double): StationInfo? =
    majorStations.minByOrNull { s ->
        val dLat = lat - s.lat
        val dLng = lng - s.lng
        sqrt(dLat * dLat + dLng * dLng)
    }

/** Looks up lat/lng for a station code; returns null if not in the curated list. */
fun stationCoordFor(code: String): StationInfo? =
    allStationsForSearch.firstOrNull { it.code.equals(code, ignoreCase = true) }

