/** Returns the full station name for a given code, falling back to the code itself. */
fun stationNameFor(code: String): String {
    val upper = code.trim().uppercase()
    return majorStations.firstOrNull { it.code.uppercase() == upper }?.name
        ?: extraStationNames[upper]
        ?: code
}

