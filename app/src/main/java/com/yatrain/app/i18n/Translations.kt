data class Language(
    val code: String,
    val nativeName: String,
    val englishName: String,
    val buttonLabel: String       // shown in the hero header pill
)

val supportedLanguages = listOf(
    Language("en", "English",   "English",   "EN"),
    Language("hi", "हिन्दी",    "Hindi",     "HI"),
    Language("mr", "मराठी",     "Marathi",   "MR"),
    Language("gu", "ગુજરાતી",   "Gujarati",  "GU"),
    Language("ta", "தமிழ்",     "Tamil",     "TA"),
    Language("te", "తెలుగు",    "Telugu",    "TE"),
    Language("kn", "ಕನ್ನಡ",     "Kannada",   "KN"),
)

fun languageByCode(code: String) =
    supportedLanguages.firstOrNull { it.code == code } ?: supportedLanguages.first()

fun stringsForCode(code: String): AppStrings = when (code) {
    "hi" -> HindiStrings
    "mr" -> MarathiStrings
    "gu" -> GujaratiStrings
    "ta" -> TamilStrings
    "te" -> TeluguStrings
    "kn" -> KannadaStrings
    else -> EnglishStrings
}

